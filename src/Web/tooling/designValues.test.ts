// @vitest-environment node
import { readdirSync, readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { createAntdTheme } from '../src/app/theme/antdTheme.ts';
import designValues from '../src/app/theme/designValues.json';
import { accountCssFile, renderAccountCss } from './accountCss.ts';

const webRoot = new URL('..', import.meta.url);
const identityApi = new URL('../Services/Identity/Flowza.Identity.Api/', webRoot);

/** Git may check text files out with Windows line endings; the content is what must match. */
const withUnixLineEndings = (text: string) => text.replace(/\r\n/g, '\n');

/** The value of one `--flowza-*` variable in a CSS text. */
function variable(css: string, name: string): string | undefined {
  return new RegExp(`${name}:\\s*([^;]+);`).exec(css)?.[1]?.trim();
}

describe('Login-page CSS from the design values (UI-02)', () => {
  const generated = renderAccountCss(designValues);

  it('UI_02_AC2_the_committed_login_css_equals_a_fresh_generation', () => {
    const committed = withUnixLineEndings(readFileSync(accountCssFile, 'utf8'));
    // If this fails: run `npm run design:css` in src/Web and commit the result.
    expect(committed).toBe(generated);
  });

  it('UI_02_AC2_login_pages_and_application_share_the_brand_colour_and_font', () => {
    const theme = createAntdTheme(designValues);
    expect(variable(generated, '--flowza-brand')).toBe(theme.token?.colorPrimary);
    expect(variable(generated, '--flowza-on-brand')).toBe(theme.token?.colorTextLightSolid);
    expect(variable(generated, '--flowza-font-family')).toBe(theme.token?.fontFamily);
    expect(variable(generated, '--flowza-font-size-base')).toBe(`${String(theme.token?.fontSize)}px`);
  });

  it('every_value_becomes_a_variable_named_by_its_path_with_pixel_units_where_needed', () => {
    expect(variable(generated, '--flowza-neutral-text-secondary')).toBe(designValues.neutral.textSecondary);
    expect(variable(generated, '--flowza-status-error-background')).toBe(
      designValues.status.error.background,
    );
    expect(variable(generated, '--flowza-space-xl')).toBe(`${String(designValues.space.xl)}px`);
    expect(variable(generated, '--flowza-font-weight-strong')).toBe(String(designValues.font.weight.strong));
    expect(variable(generated, '--flowza-shadow-card')).toBe(designValues.shadow.card);
    expect(generated).not.toContain('description');
    expect(generated).not.toContain('breakpoints');
  });

  it('says_it_is_generated_and_must_not_be_edited', () => {
    expect(generated.startsWith('/* Generated by `npm run design:css`')).toBe(true);
    expect(generated).toContain('Do not edit by hand');
  });
});

// ---- No stray values (UI-02-AC1) -------------------------------------------------------------------------------

/**
 * A CSS declaration or style property whose value holds a written size (`24px`, `1.5rem`, `16`): spacing and corners
 * come from the design values. Layout sizes (widths, positions, 1 px lines) are not design values and stay allowed.
 */
const literalSize = (properties: string) =>
  new RegExp(
    String.raw`\b(?:${properties})[\w-]*\s*:\s*(?!var\()[^;,}\n]*?(?<![\w.-])(?:\d+\.\d+|[1-9]\d*)(?:px|r?em)?(?![\w.%(])`,
    'gi',
  );

/** A colour, font or size written into a screen instead of read from the design values. */
const strayPatterns: { kind: string; pattern: RegExp }[] = [
  { kind: 'hex colour', pattern: /#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b/gi },
  { kind: 'rgb/hsl colour', pattern: /\b(?:rgba?|hsla?)\(/gi },
  {
    kind: 'named colour',
    pattern:
      /\b(?:color|background|border)(?:-?color)?\s*:\s*['"]?(?:white|black|red|green|blue|gr[ae]y|orange|yellow|purple)\b/gi,
  },
  { kind: 'font size', pattern: /\bfont-?size\s*:\s*(?!var\(|inherit)['"]?\d/gi },
  { kind: 'font weight', pattern: /\bfont-?weight\s*:\s*(?!var\(|inherit)['"]?\d/gi },
  { kind: 'font family', pattern: /\bfont-?family\s*:\s*(?!var\(|inherit)\S/gi },
  { kind: 'spacing', pattern: literalSize('padding|margin|gap|row-?gap|column-?gap') },
  { kind: 'corner radius', pattern: literalSize('border-?radius') },
];

function strayValues(text: string): string[] {
  // Comments may mention values (e.g. "brand #1f5fbf") without setting them.
  const code = text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
    .replace(/@\*[\s\S]*?\*@/g, '');
  return strayPatterns.flatMap(({ kind, pattern }) =>
    [...code.matchAll(pattern)].map((match) => `${kind}: ${match[0]}`),
  );
}

/** Files where every visual value must come from the design values: screens, their CSS and the login pages. */
function scannedFiles(): string[] {
  const web = (readdirSync(new URL('src', webRoot), { recursive: true }) as string[])
    .map((path) => `src/${path.replace(/\\/g, '/')}`)
    .filter(
      (path) => /\.(tsx|css)$/.test(path) && !/\.test\.tsx$/.test(path) && !path.startsWith('src/test/'),
    );
  const identity = (readdirSync(identityApi, { recursive: true }) as string[])
    .map((path) => path.replace(/\\/g, '/'))
    .filter(
      (path) => /^(wwwroot\/.*\.css|Pages\/.*\.cshtml)$/.test(path) && !path.endsWith('/design-values.css'),
    )
    .map((path) => `identity/${path}`);
  return [...web, ...identity].sort();
}

function read(file: string): string {
  return file.startsWith('identity/')
    ? readFileSync(new URL(file.slice('identity/'.length), identityApi), 'utf8')
    : readFileSync(new URL(file, webRoot), 'utf8');
}

/**
 * Files that still hold their own values, with the task that cleans them. The list only shrinks: it must be empty
 * when T010 is done (tasks 007).
 */
const stillToClean = new Map<string, string>([
  [
    'identity/wwwroot/account/assets/account.css',
    'T004 rewrites it as layout only, reading design-values.css',
  ],
  ['src/app/shell/AppShell.module.css', 'T007 to T009 rebuild the frame (navigation, header, phone drawer)'],
  ['src/features/admin/users/AccessSection.tsx', 'T010 restyles the user details'],
  ['src/features/admin/users/TemporaryPasswordPanel.tsx', 'T010 restyles create user'],
  ['src/features/admin/users/UserDetailsPage.tsx', 'T010 restyles the user details'],
  ['src/features/admin/users/users.module.css', 'T010 restyles the users screens'],
  ['src/features/profile/profile.module.css', 'T010 restyles my profile'],
  ['src/shared/components/ApiErrorAlert.tsx', 'T010 restyles the error states'],
]);

describe('No stray visual values (UI-02-AC1)', () => {
  it('finds_spacing_and_corners_but_not_layout_sizes_or_zero', () => {
    expect(
      strayValues('a { padding: 8px 16px; margin: 0 auto 2rem; border-radius: 4px; gap: 0.5rem; }'),
    ).toHaveLength(4);
    expect(strayValues('const style = { marginBottom: 16, borderRadius: 6 };')).toHaveLength(2);
    expect(
      strayValues(
        'a { margin: 0; width: 240px; top: -48px; border: 1px solid var(--flowza-neutral-border); }',
      ),
    ).toEqual([]);
    expect(strayValues('a { padding: var(--flowza-space-lg) var(--flowza-space-xl); }')).toEqual([]);
  });

  it('finds_colours_fonts_and_sizes_but_not_variables_or_comments', () => {
    expect(strayValues('a { color: #1f5fbf; background: rgb(0, 0, 0); font-size: 14px; }')).toHaveLength(3);
    expect(strayValues("const style = { fontSize: 14, fontFamily: 'Arial', color: 'white' };")).toHaveLength(
      3,
    );
    expect(
      strayValues(
        'a { color: var(--flowza-brand); font: inherit; font-size: var(--flowza-font-size-base); }',
      ),
    ).toEqual([]);
    expect(strayValues('/* brand #1f5fbf */ <a href="#main">')).toEqual([]);
  });

  it('UI_02_AC1_screens_and_login_pages_hold_no_colour_font_or_size_of_their_own', () => {
    const files = scannedFiles();
    expect(files.length).toBeGreaterThan(0);

    const offenders = files
      .filter((file) => !stillToClean.has(file))
      .map((file) => ({ file, values: strayValues(read(file)) }))
      .filter(({ values }) => values.length > 0);

    // Take the value from designValues.json (Ant Design token or --flowza-* variable) instead.
    expect(offenders).toEqual([]);
  });

  it('UI_02_AC1_files_still_to_clean_are_listed_only_while_they_hold_stray_values', () => {
    for (const file of stillToClean.keys()) {
      // A file that is clean (or gone) leaves the list, so the list reaches empty by T010.
      expect({ file, hasStrayValues: strayValues(read(file)).length > 0 }).toEqual({
        file,
        hasStrayValues: true,
      });
    }
  });
});
